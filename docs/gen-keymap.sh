#!/usr/bin/env bash
# Regenerate docs/keymap.md. The Hyprland table comes from the live bind table (`hyprctl binds -j`: mods, key, description
# and submap of every described bind; a Lua config reports no dispatcher text), so run it in a Hyprland session after
# editing hyprland.lua. The leader table comes from the hub rows (.config/hub/leader md); the tmux and zsh sections are
# maintained below.
#   docs/gen-keymap.sh            write docs/keymap.md
set -euo pipefail

OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/keymap.md"

hypr_table() {
  hyprctl binds -j | jq -r '
    def mods($m):
      [ (if ($m / 64 | floor) % 2 == 1 then "SUPER" else empty end),
        (if ($m / 4  | floor) % 2 == 1 then "CTRL"  else empty end),
        (if ($m / 8  | floor) % 2 == 1 then "ALT"   else empty end),
        (if $m % 2 == 1 then "SHIFT" else empty end) ];
    def keylabel: if .catch_all then "any other key" else (mods(.modmask) + [.key]) | join("+") end;
    # the 20 workspace digit binds are summarised in one row (matched by their description: Lua binds have no dispatcher text)
    [ .[]
      | select(.has_description)
      | select(.description | test("^(Move window to )?[Ww]orkspace [0-9]+$") | not)
      | { sub: .submap, key: keylabel, desc: .description } ]
    | group_by(.sub)
    | .[]
    | (if .[0].sub == "" then "### Global" else "### Submap `" + .[0].sub + "`" end),
      "",
      "| Keys | Action |",
      "|---|---|",
      (.[] | "| `\(.key)` | \(.desc) |"),
      (if .[0].sub == "" then "| `SUPER+1..0` / `SUPER+ALT+1..0` | Workspace 1-10 / 11-20 (add `SHIFT` to move the window there) |" else empty end),
      ""
  '
}

{
  cat <<'EOF'
# Keymap

Generated by `docs/gen-keymap.sh` (Hyprland part from `hyprctl binds -j`). `SUPER` is the main modifier.
`SUPER+/` opens the same list live in rofi.

## Hyprland

EOF
  hypr_table
  cat <<'EOF'
### Desktop vim grammar

Windows and workspaces follow one pattern: the modifier picks the layer, `h j k l` the direction.

| Keys | Action |
|---|---|
| `SUPER+h/j/k/l` | Focus window |
| `SUPER+SHIFT+h/j/k/l` | Move / swap window |
| `SUPER+CTRL+h/j/k/l` | Resize (repeats while held) |
| `SUPER+ALT+h` / `SUPER+ALT+l` | Previous / next tab of a group (`SUPER+Y` makes a group, `SUPER+SHIFT+Y` next tab) |
| `SUPER+ALT+j` / `SUPER+ALT+k` | Next / previous workspace on the current monitor |
| `SUPER+ALT+SHIFT+h/j/k/l` | Move the window into the group on that side; `SUPER+CTRL+Y` moves it out |
| `SUPER+[` / `SUPER+]` | Monitor (`SHIFT` moves the window, `CTRL` the workspace) |
| `SUPER+CTRL+R` | Resize mode: `h j k l` resize, any other key leaves |
| `SUPER+ALT+X` | Actions of the visible notification (dunst context menu) |
| `SUPER+;` | Leader menu (below) |

### Keyboard pointer

`wl-kbptr` and `wlrctl` (AUR) drive the pointer from the keyboard; until they are installed (`sudo ./apply-system.sh --only install`)
the binds only show a notification.

| Keys | Action |
|---|---|
| `SUPER+'` | Hint click: grid label, bisect, click (`g` / `h` / `b` = left / right / middle, Space or Enter only move the pointer) |
| `SUPER+CTRL+'` | Hint drag: pick the start point, then the end point (text selection, drag and drop) |
| `SUPER+ALT+M` | Mouse mode (`mouse` submap, shown by waybar) |

Mouse mode keys: `h j k l` move 25 px, `H J K L` move 150 px, `Space` / `Enter` left click, `r` right click, `m` middle click,
`y` / `u` scroll down / up, `f` jump by hint, `Esc` / `q` or any other key leave. wl-kbptr reads its labels from the active
layout, so `pointer.sh` switches the keyboard to us for the hint and restores the layout afterwards.

### Leader menu (`SUPER+;`)

One-shot, self-documenting which-key popup (`wlr-which-key`, AUR). The menu is generated from the hub rows
(`.config/hub/leader`, group keys in `.config/hub/leader-groups.tsv`, a `leader` column in `actions.tsv` and `actions.d/*.tsv`),
so the hub and the leader cannot drift. Keys work on the ua and ru layouts. Every item runs `hub --leader ID`.

EOF
  "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.config/hub/leader" md
  cat <<'EOF'

