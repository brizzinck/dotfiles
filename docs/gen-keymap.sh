#!/usr/bin/env bash
# Regenerate docs/keymap.md. The Hyprland table comes from the live bind table (`bindd` descriptions), so run it in a
# Hyprland session after editing hyprland.conf; the tmux and zsh sections are maintained below.
#   docs/gen-keymap.sh            write docs/keymap.md
set -euo pipefail

OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/keymap.md"

hypr_table() {
  hyprctl binds -j | jq -r '
    def mods($m):
      [ (if ($m / 64 | floor) % 2 == 1 then "SUPER" else empty end),
        (if ($m / 4  | floor) % 2 == 1 then "CTRL"  else empty end),
        (if ($m / 8  | floor) % 2 == 1 then "ALT"   else empty end),
        (if $m % 2 == 1 then "SHIFT" else empty end) ];
    def keylabel: (mods(.modmask) + [.key]) | join("+");
    # the 20 workspace digit binds are summarised in one row
    [ .[]
      | select(.has_description)
      | select((.dispatcher != "workspace" and .dispatcher != "movetoworkspace") or (.arg | test("^(prev|special)")))
      | { sub: .submap, key: keylabel, desc: .description } ]
    | group_by(.sub)
    | .[]
    | (if .[0].sub == "" then "### Global" else "### Submap `" + .[0].sub + "`" end),
      "",
      "| Keys | Action |",
      "|---|---|",
      (.[] | "| `\(.key)` | \(.desc) |"),
      (if .[0].sub == "" then "| `SUPER+1..0` / `SUPER+ALT+1..0` | Workspace 1-10 / 11-20 (add `SHIFT` to move the window there) |" else empty end),
      ""
  '
}

{
  cat <<'EOF'
# Keymap

Generated by `docs/gen-keymap.sh` (Hyprland part from `hyprctl binds -j`). `SUPER` is the main modifier.
`SUPER+/` opens the same list live in rofi.

## Hyprland

EOF
  hypr_table
  cat <<'EOF'
## tmux

Prefix is `Ctrl+Space`. Config: `.config/tmux/tmux.conf`.

| Keys | Action |
|---|---|
| `prefix \|` / `prefix -` | Split right / below, in the current directory |
| `prefix c` | New window in the current directory |
| `prefix C` | New named session (name is mandatory and unique) |
| `prefix F` | Project sessionizer: fuzzy-pick a directory, jump to or create its session |
| `prefix u` | URL picker from the pane scrollback (Enter opens, Ctrl-y copies) |
| `` prefix ` `` | Popup shell in the pane's directory |
| `prefix g` / `d` / `y` | New window running lazygit / lazydocker / yazi |
| `prefix D` | Detach |
| `prefix H/J/K/L` | Resize pane by 5 (repeatable) |
| `Ctrl+h/j/k/l` | Move between nvim splits and tmux panes |
| `Alt+h` / `Alt+l` | Previous / next window |
| `Alt+Shift+h` / `Alt+Shift+l` | Move the window left / right |
| `Alt+1..9` | Jump to window N |
| `Alt+Space` / `prefix Tab` | Last window |
| `prefix S` / `prefix R` | Save a named snapshot / restore one (fzf, `d`/`x` deletes) |
| `prefix X` | Kill-session picker |
| `prefix Q` | Kill the current session (confirm) and land in a fresh one |
| `prefix N` | Save the current session as a snapshot, then start a new unnamed one |
| `prefix r` | Reload `tmux.conf` |
| `prefix [` then `v` / `y` | Copy mode (vi): select / copy to the Wayland clipboard |
| double / triple click | Copy word / line to the clipboard |

Status badges: `PREFIX` (yellow), `COPY` (blue), `ZOOM` (purple), `SYNC` (red); a red bell marks a background window that needs attention.

## Shell helpers (`.zshrc`)

| Command | What it does |
|---|---|
| `sysup` | Upgrade: Arch news, `yay -Syu`, flatpak, pacdiff, paccache, reboot hint, failed units |
| `vpn` | fzf toggle for the VPN/proxy services that exist on this machine |
| `jf [args]` | Fuzzy journal of this boot: `jf -p err`, `jf -u docker`, `jf --user` |
| `grun [args]` | `go run` for `./main.go`, `./cmd/main.go` or `./cmd/api/main.go` (was `rg`, which shadowed ripgrep) |
| `lzd` | lazydocker (was `id`'s shadow) |
| `tp` | `trash-put`: move to the trash instead of `rm` |
| `ls` / `ll` / `lt` | eza listings (interactive shells only, not under agents) |
| `gtj` `gtd` `gtn` `gtc` `gto` | cd to `~/job`, `~/dotfiles`, the nvim config, `~/.config`, the Obsidian vault |
| `tg` / `lg` | `go test ./...` / `golangci-lint run --fix; go mod tidy` |
EOF
} >"$OUT"
echo "wrote $OUT"
