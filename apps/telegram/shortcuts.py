#!/usr/bin/env python3
"""Telegram Desktop vim-style navigation shortcuts: build / install shortcuts-custom.json.

    python3 apps/telegram/shortcuts.py build      write apps/telegram/shortcuts-custom.json (from keymap.tsv for the ua/ru keys)
    python3 apps/telegram/shortcuts.py install    copy it into the Telegram data dir (backs the old file up once)
    python3 apps/telegram/shortcuts.py check      exit 1 when shortcuts-custom.json is stale
    python3 apps/telegram/shortcuts.py where      print the data dir that install would use

Telegram reads the file at start: restart Telegram afterwards (this script never touches a running Telegram).
Run with PYTHONPYCACHEPREFIX=/tmp/pycache. Stdlib only.

Keys (the command names are the ones in tdata/shortcuts-default.json):
  Alt+j / Alt+k              next / previous chat            (defaults Alt+Down / Alt+Up stay)
  Alt+Shift+j / Alt+Shift+k  next / previous folder          (defaults Ctrl+Shift+Down / Up stay)
  Ctrl+Alt+g / Ctrl+Alt+Shift+g   first / last chat          (vim gg / G, defaults Ctrl+Alt+Home / End stay)
Telegram reads Qt key codes, which are characters, not physical keys: with the ua or ru layout active Alt+j arrives as
Alt+<Cyrillic o>. Every binding therefore also exists for the Cyrillic characters on the same physical keys (generated
from .config/layout/keymap.tsv, never typed by hand). The Cyrillic characters in shortcuts-custom.json are functional data.
"""
import json
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = HERE / "shortcuts-custom.json"
sys.path.insert(0, str(ROOT / ".config/layout"))
import layout  # noqa: E402  (the one physical-key map: .config/layout/layout.py)

BINDINGS = [
    ("next_chat", "alt+", "j"),
    ("previous_chat", "alt+", "k"),
    ("next_folder", "alt+shift+", "j"),
    ("previous_folder", "alt+shift+", "k"),
    ("first_chat", "ctrl+alt+", "g"),
    ("last_chat", "ctrl+alt+shift+", "g"),
]
HEADER = """// This is a list of your own shortcuts for Telegram Desktop
// Generated by ~/dotfiles/apps/telegram/shortcuts.py from the layout table (.config/layout/keymap.tsv), do not edit:
// vim-style chat and folder navigation, each with the Cyrillic keys of the ua and ru layouts.
// You can see full list of commands in the 'shortcuts-default.json' file
// Place a null value instead of a command string to switch the shortcut off
// You can also edit them in Settings > Chat Settings > Keyboard Shortcuts.

"""


def build():
    L = layout.Layout(layout.load_map())
    items = []
    for command, mods, key in BINDINGS:
        for k in [key] + L.twins.get(key, []):
            items.append({"command": command, "keys": mods + k})
    body = json.dumps(items, indent=4, ensure_ascii=False)
    return HEADER + body + "\n"


def data_dirs():
    home = Path.home()
    return [home / ".local/share/TelegramDesktop/tdata",
            home / ".var/app/org.telegram.desktop/data/TelegramDesktop/tdata"]


def target():
    for d in data_dirs():
        if d.is_dir():
            return d / "shortcuts-custom.json"
    return None


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "build"
    text = build()
    if cmd == "build":
        OUT.write_text(text)
        print("wrote", OUT)
    elif cmd == "check":
        if not OUT.exists() or OUT.read_text() != text:
            print("stale:", OUT)
            sys.exit(1)
    elif cmd == "where":
        t = target()
        print(t if t else "no Telegram data dir found")
        sys.exit(0 if t else 1)
    elif cmd == "install":
        t = target()
        if t is None:
            sys.exit("no Telegram data dir (~/.local/share/TelegramDesktop/tdata or the flatpak one): start Telegram once")
        if not OUT.exists() or OUT.read_text() != text:
            OUT.write_text(text)
        if t.exists() and t.read_text() == text:
            print("already installed:", t)
            return
        backup = t.with_name(t.name + ".dotfiles-orig")
        if t.exists() and not backup.exists():
            shutil.copy2(t, backup)
            print("backed up the old file once:", backup)
        tmp = t.with_name(t.name + ".tmp")
        tmp.write_text(text)
        os.replace(tmp, t)
        print("installed:", t)
        print("Restart Telegram for it to take effect (it is not restarted from here).")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
