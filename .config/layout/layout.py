# xkb key name -> W3C code (the physical key, as ghostty names it)
W3C = {"TLDE": "Backquote", "AE11": "Minus", "AE12": "Equal", "AD11": "BracketLeft", "AD12": "BracketRight",
       "BKSL": "Backslash", "AC10": "Semicolon", "AC11": "Quote", "AB08": "Comma", "AB09": "Period", "AB10": "Slash"}
for _i, _c in enumerate("1234567890"):
    W3C["AE%02d" % (_i + 1)] = "Digit" + _c
for _i, _c in enumerate("QWERTYUIOP"):
    W3C["AD%02d" % (_i + 1)] = "Key" + _c
for _i, _c in enumerate("ASDFGHJKL"):
    W3C["AC%02d" % (_i + 1)] = "Key" + _c
for _i, _c in enumerate("ZXCVBNM"):
    W3C["AB%02d" % (_i + 1)] = "Key" + _c


def ghostty_key(w3c):
    """W3C code -> ghostty's snake_case trigger name (KeyA -> key_a, BracketLeft -> bracket_left)."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", w3c).lower()


