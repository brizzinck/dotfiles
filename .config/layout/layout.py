def dump_map():
    """Rebuild keymap.tsv from libxkbcommon: layouts us,ua,ru (same as kb_layout in hyprland.lua)."""
    x = ctypes.CDLL(ctypes.util.find_library("xkbcommon"))

    class Names(ctypes.Structure):
        _fields_ = [(n, ctypes.c_char_p) for n in ("rules", "model", "layout", "variant", "options")]

    x.xkb_context_new.restype = ctypes.c_void_p
    x.xkb_keymap_new_from_names.restype = ctypes.c_void_p
    x.xkb_keymap_new_from_names.argtypes = [ctypes.c_void_p, ctypes.POINTER(Names), ctypes.c_int]
    x.xkb_keymap_key_get_name.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
    x.xkb_keymap_key_get_name.restype = ctypes.c_char_p
    x.xkb_keymap_key_get_syms_by_level.argtypes = [ctypes.c_void_p, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_uint32,
                                                   ctypes.POINTER(ctypes.POINTER(ctypes.c_uint32))]
    x.xkb_keysym_get_name.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]
    x.xkb_keysym_to_utf8.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]
    ctx = x.xkb_context_new(0)
    names = Names(None, None, b"us,ua,ru", None, b"grp:caps_toggle")
    km = x.xkb_keymap_new_from_names(ctx, ctypes.byref(names), 0)

    def sym(kc, layout, level):
        p = ctypes.POINTER(ctypes.c_uint32)()
        if x.xkb_keymap_key_get_syms_by_level(km, kc, layout, level, ctypes.byref(p)) < 1:
            return "", ""
        name = ctypes.create_string_buffer(64)
        utf = ctypes.create_string_buffer(8)
        x.xkb_keysym_get_name(p[0], name, 64)
        x.xkb_keysym_to_utf8(p[0], utf, 8)
        return utf.value.decode(), name.value.decode()

    rows = []
    for kc in range(8, 256):
        raw = x.xkb_keymap_key_get_name(km, kc)
        nm = raw.decode() if raw else ""
        if nm not in W3C:
            continue
        r = {"xkb": nm, "w3c": W3C[nm]}
        for lay, key in enumerate(("us", "ua", "ru")):
            for lvl, suf in ((0, ""), (1, "_shift")):
                ch, sy = sym(kc, lay, lvl)
                r[key + suf] = ch
                r[key + suf + "_sym"] = sy
        rows.append(r)
    order = {n: i for i, n in enumerate(W3C)}
    rows.sort(key=lambda r: order[r["xkb"]])
    with open(TSV, "w") as f:
        f.write("# Physical-key map for the layouts us, ua, ru (kb_layout = us,ua,ru). Source of truth for layout.py.\n")
        f.write("# Rebuilt from the system xkb data with `layout.py dump-map`; columns:\n")
        f.write("#   xkb key name, W3C code (ghostty trigger), then character (and _sym = xkb keysym name) per layout,\n")
        f.write("#   unshifted and _shift.\n")
        f.write("\t".join(COLS) + "\n")
        for r in rows:
            f.write("\t".join(r[c] for c in COLS) + "\n")
    print("wrote", TSV, len(rows), "keys")


def load_map():
    rows = []
    with open(TSV) as f:
        lines = [ln.rstrip("\n") for ln in f if ln.strip() and not ln.startswith("#")]
    head = lines[0].split("\t")
    for ln in lines[1:]:
        rows.append(dict(zip(head, ln.split("\t"))))
    return rows


def is_ascii(c):
    return all(ord(ch) < 128 for ch in c)


class Layout:
    """Derived lookups. twins[us_char] = ordered distinct non-ASCII characters (ua first, then ru) on the same
    physical key and shift level; to_us[cyr] = the us character (checked to be unambiguous)."""

    def __init__(self, rows):
        self.rows = rows
        self.twins = {}
        self.to_us = {}
        self.syms = {}  # us keysym name (either level: "d", "D", "bracketleft") -> keysym names of its twins
        for r in rows:
            for suf in ("", "_shift"):
                us = r["us" + suf]
                for lay in ("ua", "ru"):
                    c = r[lay + suf]
                    if not c or is_ascii(c) or c == us:
                        continue
                    if c in self.to_us and self.to_us[c] != us:
                        sys.exit(f"ambiguous: {c!r} is on both {self.to_us[c]!r} and {us!r}")
                    self.to_us[c] = us
                    lst = self.twins.setdefault(us, [])
                    if c not in lst:
                        lst.append(c)
                    names = self.syms.setdefault(r["us" + suf + "_sym"], [])
                    sn = r[lay + suf + "_sym"]
                    if sn not in names:
                        names.append(sn)

    def pairs(self):
        """(cyrillic char, us char) sorted: letters first."""
        return sorted(self.to_us.items(), key=lambda kv: (not kv[1].isalpha(), kv[1].lower(), kv[1], kv[0]))


LAYOUTS = ("us", "ua", "ru")


def convert_text(text, src, dst, L):
    """Retype `text` typed on layout `src` as the characters the same physical keys give on `dst` (shift level kept).
    Unlike the twins above this includes the ASCII positions (ru "." sits where us has "/"). A character that is not on
    a src key (or whose key has no dst character) is left unchanged; a character that sits on two keys of the src layout
    uses the first one in keymap.tsv order."""
    if src not in LAYOUTS or dst not in LAYOUTS:
        raise ValueError(f"layout must be one of {', '.join(LAYOUTS)}")
    table = {}
    for r in L.rows:
        for suf in ("", "_shift"):
            a, b = r[src + suf], r[dst + suf]
            if a and b and a not in table:
                table[a] = b
    return "".join(table.get(c, c) for c in text)


def header(comment):
    return f"{comment} {GEN_NOTE}\n"


