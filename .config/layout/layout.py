#!/usr/bin/env python3
"""Layout-independent keys: one us -> ua/ru physical-key map, generators for every tool.

The map is keymap.tsv (next to this file): one row per printable physical key with the characters (and xkb keysym
names) that key produces in the us, ua and ru layouts, unshifted and shifted. Everything else is generated from it:

  ghostty  ~/dotfiles/.config/ghostty/layout-keys.conf   Alt+<physical key> always sends ESC + the us character
  tmux     ~/dotfiles/.config/tmux/tmux-layout.conf      Cyrillic twins of every letter / M- binding (from `tmux list-keys`)
  zsh      ~/dotfiles/.config/zsh/layout-keys.zsh        Cyrillic -> us table + widget-twin helpers (Alt widgets, vi-mode)
  shell    ~/dotfiles/.config/layout/layout-keys.sh      bash helpers: rofi key lists, fzf bind twins
  nvim     ~/dotfiles/.config/nvim/lua/configs/layout_data.lua   langmap + langmapper layout strings
  rofi     ~/dotfiles/.config/rofi/layout-keys.rasi      Cyrillic keysym twins of rofi's default kb-* letter keys
  vimium   ~/dotfiles/browsers/vimium-c-mapkey.txt       Vimium C `mapKey` lines (ua/ru character -> us key); browsers/vimium-c-build.py embeds them

Usage (stdlib only; run with PYTHONPYCACHEPREFIX=/tmp/pycache):
  layout.py gen [ghostty tmux zsh shell nvim rofi vimium]   regenerate (default: all); tmux needs a running tmux server
  layout.py check                               exit 1 when a generated file differs from a fresh render
  layout.py dump-map                            rebuild keymap.tsv from the system xkb data (libxkbcommon via ctypes)

Rules: only NON-ASCII characters get twins. A layout character that is ASCII (ru has "." where us has "/", ua has
an apostrophe where us has "`") would collide with a real us key, so those positions are left alone.
"""
import ctypes
import ctypes.util
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TSV = HERE / "keymap.tsv"
COLS = ["xkb", "w3c", "us", "us_shift", "ua", "ua_shift", "ru", "ru_shift",
        "us_sym", "us_shift_sym", "ua_sym", "ua_shift_sym", "ru_sym", "ru_shift_sym"]
OUT = {
    "ghostty": ROOT / ".config/ghostty/layout-keys.conf",
    "tmux": ROOT / ".config/tmux/tmux-layout.conf",
    "zsh": ROOT / ".config/zsh/layout-keys.zsh",
    "shell": ROOT / ".config/layout/layout-keys.sh",
    "nvim": ROOT / ".config/nvim/lua/configs/layout_data.lua",
    "rofi": ROOT / ".config/rofi/layout-keys.rasi",
    "vimium": ROOT / "browsers/vimium-c-mapkey.txt",
}
GEN_NOTE = "generated by ~/dotfiles/.config/layout/layout.py from keymap.tsv, do not edit (run: layout.py gen)"

# xkb key name -> W3C code (the physical key, as ghostty names it)
W3C = {"TLDE": "Backquote", "AE11": "Minus", "AE12": "Equal", "AD11": "BracketLeft", "AD12": "BracketRight",
       "BKSL": "Backslash", "AC10": "Semicolon", "AC11": "Quote", "AB08": "Comma", "AB09": "Period", "AB10": "Slash"}
for _i, _c in enumerate("1234567890"):
    W3C["AE%02d" % (_i + 1)] = "Digit" + _c
for _i, _c in enumerate("QWERTYUIOP"):
    W3C["AD%02d" % (_i + 1)] = "Key" + _c
for _i, _c in enumerate("ASDFGHJKL"):
    W3C["AC%02d" % (_i + 1)] = "Key" + _c
for _i, _c in enumerate("ZXCVBNM"):
    W3C["AB%02d" % (_i + 1)] = "Key" + _c


def ghostty_key(w3c):
    """W3C code -> ghostty's snake_case trigger name (KeyA -> key_a, BracketLeft -> bracket_left)."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", w3c).lower()


# --------------------------------------------------------------------------------------------------------------
def dump_map():
    """Rebuild keymap.tsv from libxkbcommon: layouts us,ua,ru (same as kb_layout in hyprland.lua)."""
    x = ctypes.CDLL(ctypes.util.find_library("xkbcommon"))

    class Names(ctypes.Structure):
        _fields_ = [(n, ctypes.c_char_p) for n in ("rules", "model", "layout", "variant", "options")]

    x.xkb_context_new.restype = ctypes.c_void_p
    x.xkb_keymap_new_from_names.restype = ctypes.c_void_p
    x.xkb_keymap_new_from_names.argtypes = [ctypes.c_void_p, ctypes.POINTER(Names), ctypes.c_int]
    x.xkb_keymap_key_get_name.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
    x.xkb_keymap_key_get_name.restype = ctypes.c_char_p
    x.xkb_keymap_key_get_syms_by_level.argtypes = [ctypes.c_void_p, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_uint32,
                                                   ctypes.POINTER(ctypes.POINTER(ctypes.c_uint32))]
    x.xkb_keysym_get_name.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]
    x.xkb_keysym_to_utf8.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]
    ctx = x.xkb_context_new(0)
    names = Names(None, None, b"us,ua,ru", None, b"grp:caps_toggle")
    km = x.xkb_keymap_new_from_names(ctx, ctypes.byref(names), 0)

    def sym(kc, layout, level):
        p = ctypes.POINTER(ctypes.c_uint32)()
        if x.xkb_keymap_key_get_syms_by_level(km, kc, layout, level, ctypes.byref(p)) < 1:
            return "", ""
        name = ctypes.create_string_buffer(64)
        utf = ctypes.create_string_buffer(8)
        x.xkb_keysym_get_name(p[0], name, 64)
        x.xkb_keysym_to_utf8(p[0], utf, 8)
        return utf.value.decode(), name.value.decode()

    rows = []
    for kc in range(8, 256):
        raw = x.xkb_keymap_key_get_name(km, kc)
        nm = raw.decode() if raw else ""
        if nm not in W3C:
            continue
        r = {"xkb": nm, "w3c": W3C[nm]}
        for lay, key in enumerate(("us", "ua", "ru")):
            for lvl, suf in ((0, ""), (1, "_shift")):
                ch, sy = sym(kc, lay, lvl)
                r[key + suf] = ch
                r[key + suf + "_sym"] = sy
        rows.append(r)
    order = {n: i for i, n in enumerate(W3C)}
    rows.sort(key=lambda r: order[r["xkb"]])
    with open(TSV, "w") as f:
        f.write("# Physical-key map for the layouts us, ua, ru (kb_layout = us,ua,ru). Source of truth for layout.py.\n")
        f.write("# Rebuilt from the system xkb data with `layout.py dump-map`; columns:\n")
        f.write("#   xkb key name, W3C code (ghostty trigger), then character (and _sym = xkb keysym name) per layout,\n")
        f.write("#   unshifted and _shift.\n")
        f.write("\t".join(COLS) + "\n")
        for r in rows:
            f.write("\t".join(r[c] for c in COLS) + "\n")
    print("wrote", TSV, len(rows), "keys")


def load_map():
    rows = []
    with open(TSV) as f:
        lines = [ln.rstrip("\n") for ln in f if ln.strip() and not ln.startswith("#")]
    head = lines[0].split("\t")
    for ln in lines[1:]:
        rows.append(dict(zip(head, ln.split("\t"))))
    return rows


def is_ascii(c):
    return all(ord(ch) < 128 for ch in c)


class Layout:
    """Derived lookups. twins[us_char] = ordered distinct non-ASCII characters (ua first, then ru) on the same
    physical key and shift level; to_us[cyr] = the us character (checked to be unambiguous)."""

    def __init__(self, rows):
        self.rows = rows
        self.twins = {}
        self.to_us = {}
        self.syms = {}  # us keysym name (either level: "d", "D", "bracketleft") -> keysym names of its twins
        for r in rows:
            for suf in ("", "_shift"):
                us = r["us" + suf]
                for lay in ("ua", "ru"):
                    c = r[lay + suf]
                    if not c or is_ascii(c) or c == us:
                        continue
                    if c in self.to_us and self.to_us[c] != us:
                        sys.exit(f"ambiguous: {c!r} is on both {self.to_us[c]!r} and {us!r}")
                    self.to_us[c] = us
                    lst = self.twins.setdefault(us, [])
                    if c not in lst:
                        lst.append(c)
                    names = self.syms.setdefault(r["us" + suf + "_sym"], [])
                    sn = r[lay + suf + "_sym"]
                    if sn not in names:
                        names.append(sn)

    def pairs(self):
        """(cyrillic char, us char) sorted: letters first."""
        return sorted(self.to_us.items(), key=lambda kv: (not kv[1].isalpha(), kv[1].lower(), kv[1], kv[0]))


def header(comment):
    return f"{comment} {GEN_NOTE}\n"


# --------------------------------------------------------------------------------------------------------------
def gen_ghostty(L):
    """Ghostty (legacy key encoding) drops Alt for a non-ASCII character: Alt+в arrives as a bare в, because the
    ESC prefix is only written for a one-byte character. A keybind on the PHYSICAL key makes Alt+letter send
    ESC + the us letter whatever layout is active (identical to what the us layout sends already)."""
    out = [header("#"), "# Included from ghostty/config (config-file = ?layout-keys.conf).\n",
           "# Alt+<physical key> -> ESC + us character, so zsh/tmux/fzf/nvim M- bindings work on ua and ru too.\n"]
    for r in L.rows:
        us, w3c = r["us"], r["w3c"]
        if w3c.startswith("Digit"):
            continue  # digits are ASCII on every layout: ghostty already prefixes them
        lit = lambda ch: "\\\\" if ch == "\\" else ch
        out.append(f"keybind = alt+{ghostty_key(w3c)}=text:\\x1b{lit(us)}\n")
        if us.isalpha():
            out.append(f"keybind = alt+shift+{ghostty_key(w3c)}=text:\\x1b{r['us_shift']}\n")
    return "".join(out)


def tmux_live():
    env = {k: v for k, v in os.environ.items() if k != "TMUX"}
    try:
        res = subprocess.run(["tmux", "list-keys"], capture_output=True, text=True, env=env, check=True)
    except (OSError, subprocess.CalledProcessError):
        sys.exit("tmux: no running server to read the bindings from (start tmux first)")
    return res.stdout


BIND_RE = re.compile(r"^bind-key\s+(-r\s+)?-T\s+(\S+)\s+(\S+)\s+(.*)$")


def portable_cmd(cmd):
    """list-keys prints absolute paths: keep the file user-agnostic (home -> ~, a plugin binary found by PATH)."""
    home = os.path.expanduser("~")
    cmd = re.sub(r"(?<![\w/.-])" + re.escape(home) + r"/", "~/", cmd)
    return re.sub(r"(?<![\w.-])(?:~|/)[^\s\"']*/tmux-fingers(?= )", "tmux-fingers", cmd)


def gen_tmux(L, listing=None):
    listing = listing if listing is not None else tmux_live()
    tables = {}
    for line in listing.splitlines():
        m = BIND_RE.match(line)
        if not m:
            continue
        rep, table, tok, cmd = m.groups()
        key = re.sub(r"\\(.)", r"\1", tok)
        twins = []
        if len(key) == 1 and key in L.twins:
            twins = L.twins[key]
            mk = lambda t: t
        elif re.fullmatch(r"M-.", key) and key[2:] in L.twins:
            twins = L.twins[key[2:]]
            mk = lambda t: "M-" + t
        else:
            continue
        for t in twins:
            tables.setdefault(table, []).append(f"bind-key {'-r ' if rep else ''}-T {table} {mk(t)} {portable_cmd(cmd)}")
    out = [header("#"), "# Sourced at the end of tmux.conf (after the plugins). Every letter / M-letter binding in the\n",
           "# prefix, copy-mode and copy-mode-vi tables gets its ua/ru twin: tmux receives the Cyrillic character\n",
           "# when a Cyrillic layout is active (Ctrl keys arrive as C0 bytes and need nothing).\n",
           "# Regenerate after adding binds: layout.py gen tmux\n"]
    for table in sorted(tables):
        out.append(f"\n# --- {table}\n")
        out.extend(sorted(set(f"{ln}\n" for ln in tables[table])))
    return "".join(out)


def zq(s):
    """zsh single-quote a string."""
    return "'" + s.replace("'", "'\\''") + "'"


def gen_zsh(L):
    out = [header("#"), "# Sourced from .zshrc. LAYOUT_US_OF maps every non-ASCII ua/ru character to the us character on\n",
           "# the same physical key. Typing is never remapped: only widget bindings get twins.\n\n",
           "typeset -gA LAYOUT_US_OF\nLAYOUT_US_OF=(\n"]
    for c, us in L.pairs():
        out.append(f"  {zq(c)} {zq(us)}\n")
    out.append(""")

# layout_dup_meta KEYMAP...: for every ESC-prefixed single-character binding (Alt+letter widgets such as fzf's
# Alt-C) add the twin ESC+<Cyrillic character>. Needed only for terminals that send ESC + UTF-8 for Alt+в;
# ghostty sends ESC + the us letter (ghostty/layout-keys.conf), so this is the belt for other terminals.
layout_dup_meta() {
  emulate -L zsh
  local km line cyr us
  local -A cur
  for km in "$@"; do
    cur=()
    for line in "${(@f)$(bindkey -M $km 2>/dev/null)}"; do
      [[ $line =~ '^"\\^\\[(.)" ([^ ]+)$' ]] && cur[$match[1]]=$match[2]
    done
    for cyr us in "${(@kv)LAYOUT_US_OF}"; do
      [[ -n ${cur[$us]-} && ${cur[$us]} != undefined-key ]] && bindkey -M $km "^[$cyr" "${cur[$us]}"
    done
  done
}

# layout_dup_keys KEYMAP...: for every plain single-character binding add the twin on the Cyrillic character.
# For the vi keymaps (vicmd, viopp, visual: later stage V1); never use it on viins or emacs, it would stop
# you typing.
layout_dup_keys() {
  emulate -L zsh
  local km line cyr us
  local -A cur
  for km in "$@"; do
    cur=()
    for line in "${(@f)$(bindkey -M $km 2>/dev/null)}"; do
      [[ $line =~ '^"(\\\\.|[^\\\\^])" ([^ ]+)$' ]] && cur[${match[1]#\\\\}]=$match[2]
    done
    for cyr us in "${(@kv)LAYOUT_US_OF}"; do
      [[ -n ${cur[$us]-} && ${cur[$us]} != undefined-key ]] && bindkey -M $km "$cyr" "${cur[$us]}"
    done
  done
}
""")
    return "".join(out)


def sh_dq(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`") + '"'


def gen_shell(L):
    out = [header("#"), "# shellcheck shell=bash\n# Source it: . ~/.config/layout/layout-keys.sh\n\n",
           "# rofi keysym names of the ua/ru twins per us key name (rofi sees keysyms, not characters)\n",
           "declare -gA LK_ROFI_SYMS=(\n"]
    for sym, names in L.syms.items():
        out.append(f"  [{sh_dq(sym)}]={sh_dq(' '.join(names))}\n")
    out.append(")\n\n# the twin characters per us character (fzf, tmux and the other terminal tools receive characters)\n")
    out.append("declare -gA LK_CHARS=(\n")
    for us, chars in sorted(L.twins.items()):
        out.append(f"  [{sh_dq(us)}]={sh_dq(' '.join(chars))}\n")
    out.append(""")

# lk_rofi 'Alt+d,Alt+p' -> 'Alt+d,Alt+Cyrillic_ve,Alt+p,Alt+Cyrillic_ze,...' (rofi 2.0 takes comma-separated lists).
# Keys without a letter twin (Alt+Return) are kept as they are.
lk_rofi() {
  local specs item mod key s out=()
  IFS=',' read -ra specs <<<"$1"
  for item in "${specs[@]}"; do
    out+=("$item")
    mod=${item%+*}; key=${item##*+}
    [[ $item == *+* && -n ${LK_ROFI_SYMS[$key]-} ]] || continue
    for s in ${LK_ROFI_SYMS[$key]}; do out+=("$mod+$s"); done
  done
  local IFS=','
  printf '%s' "${out[*]}"
}

# lk_fzf_keys 'j,k,/' -> 'j,k,/,о,л' : the key names of an unbind()/rebind() list plus the twin characters.
lk_fzf_keys() {
  local specs item c out=()
  IFS=',' read -ra specs <<<"$1"
  for item in "${specs[@]}"; do
    out+=("$item")
    for c in ${LK_CHARS[$item]-}; do out+=("$c"); done
  done
  local IFS=','
  printf '%s' "${out[*]}"
}

# lk_fzf_bind 'd:execute(x)+reload(y)'  or  'j:down,k:up,q:abort' -> the same bindings plus the twin characters.
# A spec with parentheses is one binding; otherwise it is split on commas (so actions must not contain commas).
lk_fzf_bind() {
  local spec=$1 items item key act c out=()
  if [[ $spec == *'('* ]]; then
    items=("$spec")
  else
    IFS=',' read -ra items <<<"$spec"
  fi
  for item in "${items[@]}"; do
    key=${item%%:*}; act=${item#*:}
    out+=("$item")
    for c in ${LK_CHARS[$key]-}; do out+=("$c:$act"); done
  done
  local IFS=','
  printf '%s' "${out[*]}"
}
""")
    return "".join(out)


def lua_str(s):
    return "[=[" + s + "]=]"


def gen_nvim(L):
    # langmap: only non-ASCII -> us, "from;to" with ; , \\ escaped on the to side
    esc = lambda ch: "\\" + ch if ch in ";,\\" else ch
    pairs = L.pairs()
    froms = "".join(c for c, _ in pairs)
    tos = "".join(esc(u) for _, u in pairs)
    langmap = froms + ";" + tos
    # langmapper layout strings: the positions of default_layout; an ASCII layout char stays the us char (identity)
    default = "ABCDEFGHIJKLMNOPQRSTUVWXYZ" + '<>:"{}~' + "abcdefghijklmnopqrstuvwxyz" + ",.;'[]`" + "\\|"
    at = {}
    for r in L.rows:
        for suf in ("", "_shift"):
            at[r["us" + suf]] = (r["ua" + suf], r["ru" + suf])

    def layout(idx):
        out = ""
        for u in default:
            c = at[u][idx]
            out += c if c and not is_ascii(c) else u
        return out

    out = [f"-- {GEN_NOTE}\n", "-- Consumed by lua/configs/langmapper.lua: langmap (built-in normal/visual/operator\n",
           "-- commands) and the layout strings for langmapper.nvim (mappings: <leader>, <C-x>, <M-x>, g-prefixes).\n",
           "return {\n", f"  langmap = {lua_str(langmap)},\n", f"  default_layout = {lua_str(default)},\n",
           "  layouts = {\n", f"    ua = {lua_str(layout(0))},\n", f"    ru = {lua_str(layout(1))},\n", "  },\n}\n"]
    return "".join(out)


# The app launcher keeps rofi (it has no modes), so it gets the list grammar of fzf-menu as closely as rofi allows:
# Ctrl+j/k move, Ctrl+d/u page, Esc cancels (Ctrl+j/k/d/u lose their readline meanings: accept stays on Enter / Ctrl+m,
# delete-forward on Delete). Applied to rofi's defaults before the Cyrillic twins are added.
ROFI_OVERRIDES = {
    "kb-accept-entry": "Return,KP_Enter,Control+m",
    "kb-remove-to-eol": "",
    "kb-remove-char-forward": "Delete",
    "kb-remove-to-sol": "",
    "kb-row-up": "Up,Control+p,Control+k",
    "kb-row-down": "Down,Control+n,Control+j",
    "kb-page-prev": "Page_Up,Control+u",
    "kb-page-next": "Page_Down,Control+d",
}


def gen_rofi(L):
    """rofi sees keysyms, not characters: every default kb-* binding that has a Control+/Alt+<letter> part gets the
    Cyrillic keysym twins (Control+p -> Control+p,Control+Cyrillic_ze). Needs rofi installed for its defaults."""
    try:
        dump = subprocess.run(["rofi", "-no-config", "-dump-config"], capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        sys.exit("rofi: cannot dump the default config")
    out = [header("//"), "// Imported by rofi/config.rasi. Default kb-* bindings plus the ua/ru twins of their letter keys\n",
           "// (custom keys passed by the scripts use lk_rofi from ~/.config/layout/layout-keys.sh).\n", "configuration {\n"]
    for m in re.finditer(r'^/\*\s*(kb-[a-z0-9-]+):\s*"([^"]*)";\*/$', dump, re.M):
        name, val = m.groups()
        if name.startswith("kb-custom"):
            continue
        val = ROFI_OVERRIDES.get(name, val)
        specs = [x for x in val.split(",") if x]
        new = []
        for spec in specs:
            new.append(spec)
            mod, plus, key = spec.rpartition("+")
            if plus and mod and key in L.syms:
                new.extend(f"{mod}+{t}" for t in L.syms[key])
        if len(new) > len(specs) or name in ROFI_OVERRIDES:
            out.append(f'  {name}: "{",".join(new)}";\n')
    out.append("}\n")
    return "".join(out)


def gen_vimium(L):
    """Vimium C `mapKey <character> <key>` lines (Vimium C only sees characters, so every layout's non-ASCII
    character is translated to the us key). A letter key needs only the lower-case character: Vimium C turns
    Shift+<mapped letter> into the upper-case key itself; a symbol or digit key gets both levels. A backslash target
    is written `\\\\` (a single trailing backslash would be a line continuation)."""
    out = ["# " + GEN_NOTE + "\n",
           "# Vimium C mapKey block for the ua and ru layouts, embedded in browsers/vimium-c.json by browsers/vimium-c-build.py.\n",
           "# ASCII characters of a layout (ru: . and , on the slash key) are left alone, as everywhere in this tool.\n"]
    seen = set()
    for r in L.rows:
        levels = ("",) if r["us"].isalpha() else ("", "_shift")
        for suf in levels:
            us = r["us" + suf]
            for lay in ("ua", "ru"):
                c = r[lay + suf]
                if not c or is_ascii(c) or c in seen:
                    continue
                seen.add(c)
                out.append(f"mapKey {c} {'\\\\' if us == chr(92) else us}\n")
    return "".join(out)


GENS = {"ghostty": gen_ghostty, "tmux": gen_tmux, "zsh": gen_zsh, "shell": gen_shell, "nvim": gen_nvim, "rofi": gen_rofi,
        "vimium": gen_vimium}


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "gen"
    if cmd == "dump-map":
        return dump_map()
    L = Layout(load_map())
    want = argv[2:] or list(GENS)
    if cmd == "gen":
        for name in want:
            text = GENS[name](L)
            OUT[name].parent.mkdir(parents=True, exist_ok=True)
            OUT[name].write_text(text)
            print("wrote", OUT[name])
    elif cmd == "check":
        bad = 0
        for name in want:
            if name in ("tmux", "rofi"):
                continue  # depend on the running tmux server / the installed rofi
            if not OUT[name].exists() or OUT[name].read_text() != GENS[name](L):
                print("stale:", OUT[name])
                bad = 1
        sys.exit(bad)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
