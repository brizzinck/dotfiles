# shellcheck shell=bash
# vimfzf: the one shared fzf front end (Telescope-like modal list). Source it from a script:
#
#   . ~/.config/fzf/vimfzf.sh
#   VF_PROMPT=pick                       # label of the prompt (default: fzf)
#   VF_NORMAL_BINDS=('d:execute(...)')   # optional extra NORMAL-mode letter binds (twins are added)
#   printf '%s\n' a b c | vimfzf -m --preview 'echo {}'
#
# or call the executable `fzf-menu --here ARGS` (python, zsh, one-liners). `fzf-menu` without --here opens the
# same list in a floating terminal (for keybinds). Every argument of vimfzf goes to fzf unchanged.
#
# INSERT (the list opens in it)      NORMAL (Esc)
#   typing        filter               j / k          down / up              Esc, q    quit
#   Ctrl+j/k n/p  down / up            g / G          first / last           Enter     accept
#   Ctrl+d / u    half page down/up    Ctrl+d / u     half page down/up
#   Enter         accept               i a I A /      back to INSERT (typing resumes)
#   Esc           NORMAL               c              clear the query + INSERT        x   clear the query
#   Alt+j / k     scroll the preview   J / K          scroll the preview     p   toggle the preview
#   Tab / Shift+Tab  multi-select      v              mark + down (with -m)  Ctrl+f / b  page down / up
# fzf has no key sequences: `g` alone goes to the top (there is no `gg`). In NORMAL every other printable key is
# ignored, so a stray key never edits the query; the filter typed in INSERT stays applied while you navigate.
# The mode shows in the prompt: [I] green, [N] yellow (terminal palette = the active Everforest variant).
# Every letter bind has its ua/ru twin characters (lk_fzf_bind of ~/.config/layout/layout-keys.sh), so NORMAL
# works on the Cyrillic layouts too. Colours come from FZF_DEFAULT_OPTS_FILE (generated by themes/palette).
#
# Callers may set: VF_PROMPT, VF_NORMAL_BINDS (array of KEY:ACTION), VF_MODAL=0 (plain fzf with only the colours).
# Test hooks: vimfzf_print prints the fzf argument vector instead of running it.

: "${XDG_STATE_HOME:=$HOME/.local/state}"
: "${XDG_CONFIG_HOME:=$HOME/.config}"
if [[ -z ${FZF_DEFAULT_OPTS_FILE:-} && -r $XDG_STATE_HOME/theme/current/fzfrc ]]; then
  export FZF_DEFAULT_OPTS_FILE="$XDG_STATE_HOME/theme/current/fzfrc"
fi
# lazygit-style fallback: a missing file must not break fzf
[[ -n ${FZF_DEFAULT_OPTS_FILE:-} && ! -r $FZF_DEFAULT_OPTS_FILE ]] && unset FZF_DEFAULT_OPTS_FILE

# shellcheck source=/dev/null
. "$XDG_CONFIG_HOME/layout/layout-keys.sh" 2>/dev/null || {
  declare -gA LK_CHARS=()
  lk_fzf_bind() { printf '%s' "$1"; }
}

# printable ASCII keys fzf can bind as plain characters (space is the key name `space`)
_vf_ascii_keys() {
  local i c
  for ((i = 33; i <= 126; i++)); do
    printf -v c '%b' "\\$(printf '%03o' "$i")"
    printf '%s\n' "$c"
  done
  printf 'space\n'
}

# _vf_key_list PREFIX KEY...: an unbind()/rebind() action chain for the keys. fzf lists use commas, so `(`, `)`
# need their own delimiter (|...|) and the others are collected into one parenthesised list.
_vf_key_chain() {
  local verb=$1 k plain=() out=''
  shift
  for k in "$@"; do
    case $k in
      '(' | ')') out+="+$verb|$k|" ;;
      *) plain+=("$k") ;;
    esac
  done
  local IFS=','
  printf '%s' "$verb(${plain[*]})$out"
}

# vf_color_prompt MODE: prompt text with the coloured mode tag (SGR 32 = palette green, 33 = palette yellow)
_vf_prompt() {
  local mode=$1 label=${VF_PROMPT:-fzf}
  case $mode in
    N) printf '\033[1;33m[N]\033[0m %s> ' "$label" ;;
    *) printf '\033[1;32m[I]\033[0m %s> ' "$label" ;;
  esac
}

# _vf_action VERB TEXT: the fzf action VERB<d>TEXT<d'> for caller-provided TEXT. fzf ends the argument at the first
# closing delimiter, so the pair is the first of ( ) [ ] { } < > ~ ! @ # $ % ^ & * ; / | whose characters are not in
# TEXT; only when every pair occurs in TEXT are the closing characters of the last pair removed from it.
_vf_action() {
  local verb=$1 text=$2 pair o c
  for pair in '()' '[]' '{}' '<>' '~~' '!!' '@@' '##' '$$' '%%' '^^' '&&' '**' ';;' '//' '||'; do
    o=${pair:0:1} c=${pair:1:1}
    [[ $text == *"$o"* || $text == *"$c"* ]] && continue
    printf '%s%s%s%s' "$verb" "$o" "$text" "$c"
    return 0
  done
  text=${text//"$c"/}
  printf '%s%s%s%s' "$verb" "$o" "$text" "$c"
}

# fills the array VF_ARGS with the fzf arguments for the modal behaviour
_vf_build() {
  local k t spec key a
  local -A act=() norm=()
  VF_ARGS=()
  [[ ${VF_MODAL:-1} == 0 ]] && return 0

  # NORMAL-mode letter actions (us key => action), caller binds win
  act=(
    [j]=down [k]=up [g]=first [G]=last [q]=abort
    [i]=@INSERT [a]=@INSERT [I]=@INSERT [A]=@INSERT ['/']=@INSERT
    [c]='clear-query+@INSERT' [x]=clear-query
    [p]=toggle-preview [J]=preview-half-page-down [K]=preview-half-page-up
    [v]='toggle+down'
  )
  for spec in "${VF_NORMAL_BINDS[@]+"${VF_NORMAL_BINDS[@]}"}"; do
    key=${spec%%:*}
    act[$key]=${spec#*:}
  done

  local -a all=() chain_keys=()
  while IFS= read -r k; do all+=("$k"); done < <(_vf_ascii_keys)
  local -a keys=("${all[@]}")
  # twins (Cyrillic characters) of every key that has one; they get the action of their us key
  local -A twin_of=()
  for k in "${keys[@]}"; do
    [[ $k == space ]] && continue
    for t in ${LK_CHARS[$k]-}; do twin_of[$t]=$k; all+=("$t"); done
  done
  # caller binds may name keys outside the printable set (none today); they are bound as given
  for k in "${all[@]}"; do
    chain_keys+=("$k")
    key=${twin_of[$k]:-$k}
    a=${act[$key]:-ignore}
    [[ $a == *'@INSERT'* ]] && a=${a//@INSERT/__INSERT__}
    norm[$k]=$a
  done

  local to_insert to_normal
  to_insert="$(_vf_action change-prompt "$(_vf_prompt I)")+$(_vf_key_chain unbind "${chain_keys[@]}")"
  to_normal="$(_vf_action change-prompt "$(_vf_prompt N)")+$(_vf_key_chain rebind "${chain_keys[@]}")"
  export VF_ACT_NORMAL=$to_normal

  # the printable keys: bound to their NORMAL action (or ignore), then unbound at start so INSERT types
  for k in "${chain_keys[@]}"; do
    a=${norm[$k]}
    a=${a//__INSERT__/"$to_insert"}
    VF_ARGS+=(--bind "$k:$a")
  done
  # shellcheck disable=SC2016 # the transform snippet runs inside fzf, where $FZF_PROMPT is expanded
  VF_ARGS+=(
    --bind "start:$to_insert"
    # Esc: INSERT -> NORMAL, NORMAL -> quit (decided by the mode tag in the prompt)
    --bind 'esc:transform:case "$FZF_PROMPT" in *"[N]"*) echo abort ;; *) echo "$VF_ACT_NORMAL" ;; esac'
    --bind 'ctrl-j:down' --bind 'ctrl-k:up' --bind 'ctrl-n:down' --bind 'ctrl-p:up'
    --bind 'ctrl-d:half-page-down' --bind 'ctrl-u:half-page-up'
    --bind 'ctrl-f:page-down' --bind 'ctrl-b:page-up'
    --bind 'alt-j:preview-down' --bind 'alt-k:preview-up'
    --prompt "$(_vf_prompt I)"
    --ansi --layout=reverse --height=100% --border=none --info=inline-right --cycle
  )
}

# vimfzf [fzf args...]: stdin = the rows, stdout = the selection (fzf exit codes: 0 ok, 1 no match, 130 cancelled)
vimfzf() {
  command -v fzf >/dev/null 2>&1 || { echo "vimfzf: fzf is not installed" >&2; return 127; }
  local VF_ARGS=()
  _vf_build
  if [[ -n ${VF_PRINT:-} ]]; then printf '%s\n' "${VF_ARGS[@]}" "$@"; return 0; fi
  # one known shell for transform/execute snippets; the caller's own shell is irrelevant here
  SHELL=/bin/bash fzf "${VF_ARGS[@]}" "$@"
}

# vimfzf_confirm "question": yes/no list (no first). Status 0 only for "yes".
vimfzf_confirm() {
  local a VF_PROMPT="${1:-sure}?"
  a=$(printf 'no\nyes\n' | vimfzf --height=100% --no-info) || return 1
  [[ $a == yes ]]
}
