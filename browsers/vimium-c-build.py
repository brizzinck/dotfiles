#!/usr/bin/env python3
"""Build browsers/vimium-c.json, the settings file to import in Vimium C (Options > Backup and restore > Import settings).

    PYTHONPYCACHEPREFIX=/tmp/pycache python3 browsers/vimium-c-build.py [--variant black|night] [--check]

Inputs (all committed, nothing is read from the browser):
  vimium-c-mapkey.txt                    mapKey block for ua/ru, generated by .config/layout/layout.py from keymap.tsv
  ../themes/generated/<variant>/vimium-c.css   look of hints, HUD, find bar and Vomnibar, rendered from the palette
  KEY_MAPPINGS, EXCLUSIONS (below)       the rest
Vimium C's own defaults stay in force (j/k h/l gg/G d/u f/F H/L J/K x/X o/O b/B T yy yf p/P gi gs / n/N v/V ...): the file only
adds to them. Importing REPLACES every other stored option with its default, so import it into a fresh or backed-up setup.
Stdlib only, deterministic; --check exits 1 when vimium-c.json is stale.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

# Extra key mappings on top of the defaults (one per line; the mapKey block is appended). Kept small on purpose: the
# defaults already are the vim grammar this setup wants (research-vim.md section 2.9).
KEY_MAPPINGS = [
    "# dotfiles: Vimium C defaults stay (j k h l gg G d u f F H L J K x X o O b B T yy yf p P gi gs / n N v V).",
    "# Ctrl+[ already acts as Esc in Vimium C. Below: the same keys on the ua and ru layouts (mapKey, generated).",
]

# (pattern, passKeys): a ':' prefix is a URL prefix; empty passKeys = Vimium C is off on that site. passKeys are the keys
# the page keeps (YouTube player: f fullscreen, m mute, k/j/l pause and seek, c captions, t theatre, i miniplayer, space).
EXCLUSIONS = [
    (":https://www.youtube.com/", "f m k j l c t i <space>"),
    (":https://mail.google.com/", ""),
    (":https://docs.google.com/", ""),
    (":https://outlook.live.com/", ""),
    (":https://outlook.office.com/", ""),
    (":https://outlook.office365.com/", ""),
    (":https://mail.proton.me/", ""),
]


def lines(text):
    """Vimium C's export format for a multi-line string option: a list of lines with a trailing empty string."""
    return text.rstrip("\n").split("\n") + [""]


def build(variant):
    css = (ROOT / "themes/generated" / variant / "vimium-c.css").read_text()
    mapkey = [ln for ln in (HERE / "vimium-c-mapkey.txt").read_text().splitlines() if ln.strip()]
    doc = {
        "name": "Vimium C",
        "description": f"dotfiles: ua/ru mapKey, pass keys for YouTube, mail/docs exclusions, Everforest {variant}",
        "environment": {"platform": "linux"},
        "exclusionRules": [{"pattern": p, "passKeys": k} for p, k in EXCLUSIONS],
        "keyMappings": KEY_MAPPINGS + mapkey + [""],
        "userDefinedCss": lines(css),
    }
    return json.dumps(doc, indent="\t", ensure_ascii=False) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variant", default="black", choices=["black", "night"])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=str(HERE / "vimium-c.json"))
    args = ap.parse_args()
    text = build(args.variant)
    out = Path(args.out)
    if args.check:
        if not out.exists() or out.read_text() != text:
            print("stale:", out)
            sys.exit(1)
        return
    out.write_text(text)
    print("wrote", out)


if __name__ == "__main__":
    main()
