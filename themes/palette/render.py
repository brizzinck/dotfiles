#!/usr/bin/env python3
"""Render the Everforest palette into per-app fragments for every variant.

    PYTHONPYCACHEPREFIX=/tmp/pycache python3 themes/palette/render.py          # write themes/generated/
    PYTHONPYCACHEPREFIX=/tmp/pycache python3 themes/palette/render.py --check  # exit 1 if generated/ is stale

Input : everforest.json (tokens, per variant) and templates/*.tmpl
Output: ../generated/<variant>/<template name without .tmpl>, plus tokens.json and tokens.css, plus
        everforest-<variant>.tdesktop-theme (zip of telegram.colors + a solid background.png, for Telegram Desktop)
Stdlib only and deterministic: running it twice yields no git diff.

Template syntax: {{name}} or {{name|filter}}.
  names   every token of the variant (bg, fg, green, diff_add_bg, ...), ansi0..ansi15, variant, title,
          faint_opacity, minimum_contrast
  filters nohash  "#abc682" -> "abc682" (Hyprland rgba(), Telegram)
          rgb     "#abc682" -> "171,198,130" (CSS rgba(), waybar)
Unknown names are an error, so a typo can never ship an empty colour.
"""
import argparse
import io
import json
import re
import struct
import sys
import zipfile
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "everforest.json"
TEMPLATES = HERE / "templates"
OUT = HERE.parent / "generated"
HEX = re.compile(r"^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$")
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_]+)(?:\|([a-z]+))?\s*\}\}")


def load():
    data = json.loads(SRC.read_text())
    shared = data["shared"]
    variants = {}
    for vname, var in data["variants"].items():
        tokens = {**shared["tokens"], **var["tokens"]}
        for key, val in tokens.items():
            if not HEX.match(val):
                sys.exit(f"{vname}.{key}: not a hex colour: {val!r}")
        ansi = [tokens[n] for n in shared["ansi_order"]]
        names = dict(tokens)
        names.update({f"ansi{i}": c for i, c in enumerate(ansi)})
        names.update(
            variant=vname,
            title=var["title"],
            faint_opacity=str(var["faint_opacity"]),
            minimum_contrast=str(shared["minimum_contrast"]),
        )
        variants[vname] = {"names": names, "tokens": tokens, "ansi": ansi, "title": var["title"],
                           "faint_opacity": var["faint_opacity"], "minimum_contrast": shared["minimum_contrast"]}
    return data["default"], variants


def apply_filter(value, flt, where):
    if flt is None:
        return value
    if not HEX.match(value):
        sys.exit(f"{where}: filter |{flt} needs a colour, got {value!r}")
    if flt == "nohash":
        return value[1:]
    if flt == "rgb":
        return ",".join(str(int(value[i:i + 2], 16)) for i in (1, 3, 5))
    sys.exit(f"{where}: unknown filter |{flt}")


def render_template(text, names, where):
    def sub(m):
        name, flt = m.group(1), m.group(2)
        if name not in names:
            sys.exit(f"{where}: unknown placeholder {{{{{name}}}}}")
        return apply_filter(names[name], flt, where)

    return PLACEHOLDER.sub(sub, text)


def tokens_json(var, vname):
    doc = {
        "variant": vname,
        "title": var["title"],
        "faint_opacity": var["faint_opacity"],
        "minimum_contrast": var["minimum_contrast"],
        "tokens": var["tokens"],
        "ansi": var["ansi"],
    }
    return json.dumps(doc, indent=2) + "\n"


def tokens_css(var, vname):
    lines = [
        f"/* Generated by themes/palette/render.py (variant: {vname}). Do not edit. */",
        ":root {",
    ]
    for key, val in var["tokens"].items():
        lines.append(f"  --ef-{key.replace('_', '-')}: {val};")
    for i, val in enumerate(var["ansi"]):
        lines.append(f"  --ef-ansi-{i}: {val};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def solid_png(hexcolour, size=16):
    """Minimal uncompressed (stored deflate) RGB PNG filled with one colour; byte-for-byte deterministic."""
    r, g, b = (int(hexcolour[i:i + 2], 16) for i in (1, 3, 5))
    raw = b"".join(b"\x00" + bytes((r, g, b)) * size for _ in range(size))

    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 0)) + chunk(b"IEND", b"")


def tdesktop_theme(colors_text, bg):
    """Telegram theme archive: colors.tdesktop-theme + background.png (stored, fixed timestamps, no extra attrs)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as z:
        for name, data in (("colors.tdesktop-theme", colors_text.encode()), ("background.png", solid_png(bg))):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    return buf.getvalue()


def build():
    default, variants = load()
    files = {}
    for vname, var in variants.items():
        files[Path(vname) / "tokens.json"] = tokens_json(var, vname)
        files[Path(vname) / "tokens.css"] = tokens_css(var, vname)
        for tmpl in sorted(TEMPLATES.glob("*.tmpl")):
            out_name = tmpl.name[: -len(".tmpl")]
            files[Path(vname) / out_name] = render_template(tmpl.read_text(), var["names"], f"{tmpl.name} [{vname}]")
        colours = files.get(Path(vname) / "telegram.colors")
        if colours is not None:
            files[Path(vname) / f"everforest-{vname}.tdesktop-theme"] = tdesktop_theme(colours, var["tokens"]["bg"])
    return default, files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 when generated/ differs")
    args = ap.parse_args()
    _, files = build()
    stale = []
    for rel, text in sorted(files.items()):
        path = OUT / rel
        data = text if isinstance(text, bytes) else text.encode()
        if path.exists() and path.read_bytes() == data:
            continue
        stale.append(str(rel))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    extra = sorted(str(p.relative_to(OUT)) for p in OUT.rglob("*") if p.is_file() and p.relative_to(OUT) not in files) if OUT.exists() else []
    if args.check:
        for s in stale:
            print(f"stale: {s}", file=sys.stderr)
        for s in extra:
            print(f"orphan (no template): {s}", file=sys.stderr)
        return 1 if stale or extra else 0
    for s in extra:
        print(f"note: {s} has no template any more (delete it by hand)", file=sys.stderr)
    print(f"rendered {len(files)} files, {len(stale)} changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
