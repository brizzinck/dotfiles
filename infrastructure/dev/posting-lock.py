#!/usr/bin/python3 -I
"""Write posting-requirements.txt: every package of the installed posting pipx venv, pinned, with ALL sha256 hashes PyPI lists for
that version (sdist and wheels), so `pip install --require-hashes` accepts exactly these files and nothing newer. Needs network.
Recipe to bump posting: `pipx install --force posting==NEW`, then `./posting-lock.py`, then change POSTING_VERSION in
user-tools.sh and the pin in sysup, run tests/dev/run.sh, commit both files. Python 3 stdlib only."""
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

OUT = Path(__file__).with_name("posting-requirements.txt")


def freeze():
    p = subprocess.run(["pipx", "runpip", "posting", "freeze"], capture_output=True, text=True, check=True)
    return [l.strip() for l in p.stdout.splitlines() if re.match(r"^[A-Za-z0-9_.-]+==[^=\s]+$", l.strip())]


def hashes(name, ver):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=30) as r:
        data = json.load(r)
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def main():
    lines = ["# GENERATED by posting-lock.py from the posting pipx venv; hashes are every file PyPI lists for the pinned version.",
             "# Installed by user-tools.sh with `pip install --require-hashes --no-deps` (dependencies are resolved here, not by pip)."]
    for spec in sorted(freeze(), key=str.lower):
        name, ver = spec.split("==")
        hs = hashes(name, ver)
        if not hs:
            sys.exit(f"no hashes for {spec}")
        lines.append(f"{name}=={ver} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hs))
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines) - 2} packages)")


if __name__ == "__main__":
    main()
